#!/usr/bin/env python3
"""
Helper script to generate SWIG Java wrappers, compile Java classes, and build purpleair-api.jar.
Used by java/meson.build.
"""

import os
import pathlib
import shutil
import subprocess
import sys
import tempfile


def main():
    if len(sys.argv) < 9:
        print(
            "Usage: build_jar.py <swig> <javac> <jar> <swig_iface> <swig_inc> <wrap_cpp_out> <jar_out> <swig_in>",
            file=sys.stderr,
        )
        sys.exit(1)

    swig = sys.argv[1]
    javac = sys.argv[2]
    jar_prog = sys.argv[3]
    swig_iface = sys.argv[4]
    swig_inc = sys.argv[5]
    wrap_cpp_out = sys.argv[6]
    jar_out = sys.argv[7]
    swig_in = sys.argv[8]

    tmp_dir = tempfile.mkdtemp()
    src_dir = os.path.join(tmp_dir, "src", "com", "purpleair", "api")
    classes_dir = os.path.join(tmp_dir, "classes")
    os.makedirs(src_dir, exist_ok=True)
    os.makedirs(classes_dir, exist_ok=True)

    try:
        # 1. Run SWIG to generate C++ JNI wrapper and Java sources
        subprocess.run(
            [
                swig,
                "-c++",
                "-java",
                "-package",
                "com.purpleair.api",
                "-I" + swig_iface,
                "-I" + swig_inc,
                "-outdir",
                src_dir,
                "-o",
                wrap_cpp_out,
                swig_in,
            ],
            check=True,
        )

        # 2. Find all generated .java files
        java_files = [str(p) for p in pathlib.Path(src_dir).glob("*.java")]
        if not java_files:
            print("ERROR: No .java files were generated by SWIG", file=sys.stderr)
            sys.exit(1)

        # 3. Compile with javac
        subprocess.run([javac, "-d", classes_dir] + java_files, check=True)

        # 4. Package into JAR
        subprocess.run(
            [jar_prog, "cf", os.path.abspath(jar_out), "-C", classes_dir, "."],
            check=True,
        )
    finally:
        shutil.rmtree(tmp_dir, ignore_errors=True)


if __name__ == "__main__":
    main()
