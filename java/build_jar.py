#!/usr/bin/env python3
"""
Helper script to generate SWIG Java wrappers, compile Java classes, and build purpleair-api.jar.
Used by java/meson.build.
"""

import os
import pathlib
import shutil
import subprocess
import sys
import tempfile


def resolve_executable(name: str) -> str:
    """Find and validate trusted system executable."""
    found = shutil.which(name)
    if not found:
        raise FileNotFoundError(f"Required tool not found in PATH: {name}")
    return os.path.abspath(found)


def main():
    if len(sys.argv) < 6:
        print(
            "Usage: build_jar.py <swig_iface> <swig_inc> <wrap_cpp_out> <jar_out> <swig_in>",
            file=sys.stderr,
        )
        sys.exit(1)

    swig_iface = str(pathlib.Path(sys.argv[1]).resolve())
    swig_inc = str(pathlib.Path(sys.argv[2]).resolve())
    wrap_cpp_out = str(pathlib.Path(sys.argv[3]).resolve())
    jar_out = str(pathlib.Path(sys.argv[4]).resolve())
    swig_in = str(pathlib.Path(sys.argv[5]).resolve())

    swig_bin = resolve_executable("swig")
    javac_bin = resolve_executable("javac")
    jar_bin = resolve_executable("jar")

    tmp_dir = tempfile.mkdtemp()
    src_dir = os.path.join(tmp_dir, "src", "com", "purpleair", "api")
    classes_dir = os.path.join(tmp_dir, "classes")
    os.makedirs(src_dir, exist_ok=True)
    os.makedirs(classes_dir, exist_ok=True)

    try:
        # 1. Run SWIG to generate C++ JNI wrapper and Java sources
        subprocess.run(
            [
                swig_bin,
                "-c++",
                "-java",
                "-package",
                "com.purpleair.api",
                "-I" + swig_iface,
                "-I" + swig_inc,
                "-outdir",
                src_dir,
                "-o",
                wrap_cpp_out,
                swig_in,
            ],
            check=True,
        )

        # 2. Find all generated .java files
        java_files = [str(p.resolve()) for p in pathlib.Path(src_dir).glob("*.java")]
        if not java_files:
            print("ERROR: No .java files were generated by SWIG", file=sys.stderr)
            sys.exit(1)

        # 3. Compile with javac
        subprocess.run([javac_bin, "-d", classes_dir] + java_files, check=True)

        # 4. Package into JAR
        subprocess.run(
            [jar_bin, "cf", jar_out, "-C", classes_dir, "."],
            check=True,
        )
    finally:
        shutil.rmtree(tmp_dir, ignore_errors=True)


if __name__ == "__main__":
    main()
